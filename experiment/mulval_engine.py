def generate_mulval_input(output_dir: str):
    """
    Generates 5 distinct Datalog input_w*.P files for MulVAL.
    Simulates a temporal attack progression where conditions change over time.
    """
    # Base facts that exist across all windows
    base_facts = """
attackerLocated(internet).
attackGoal(execCode(workstation, root)).
hacl(internet, webserver, tcp, 80).
hacl(webserver, workstation, tcp, 22).
networkServiceInfo(webserver, httpd, tcp, 80, root).
networkServiceInfo(workstation, sshd, tcp, 22, root).
"""
    
    # We will simulate the attack progressing:
    # W0: Recon (no vulns exposed)
    # W1: Web vuln exposed
    # W2: Web vuln exploited, SSH vuln exposed
    # W3: SSH vuln exploited
    # W4: Full compromise persists
    
    window_facts = {
        0: base_facts,
        1: base_facts + "hasVuln(webserver, vul_web, httpd).\nvulExists(webserver, vul_web, httpd).\nvulProperty(vul_web, remoteExploit, privEscalation).\n",
        2: base_facts + "hasVuln(webserver, vul_web, httpd).\nvulExists(webserver, vul_web, httpd).\nvulProperty(vul_web, remoteExploit, privEscalation).\nhasVuln(workstation, vul_ssh, sshd).\nvulExists(workstation, vul_ssh, sshd).\nvulProperty(vul_ssh, remoteExploit, privEscalation).\n",
        3: base_facts + "hasVuln(webserver, vul_web, httpd).\nvulExists(webserver, vul_web, httpd).\nvulProperty(vul_web, remoteExploit, privEscalation).\nhasVuln(workstation, vul_ssh, sshd).\nvulExists(workstation, vul_ssh, sshd).\nvulProperty(vul_ssh, remoteExploit, privEscalation).\n",
        4: base_facts + "hasVuln(webserver, vul_web, httpd).\nvulExists(webserver, vul_web, httpd).\nvulProperty(vul_web, remoteExploit, privEscalation).\nhasVuln(workstation, vul_ssh, sshd).\nvulExists(workstation, vul_ssh, sshd).\nvulProperty(vul_ssh, remoteExploit, privEscalation).\n"
    }

    generated_files = []
    for w in range(5):
        input_path = os.path.join(output_dir, f"input_w{w}.P")
        with open(input_path, 'w') as f:
            f.write(f"% MulVAL input for Window {w}\n")
            f.write(window_facts[w])
        generated_files.append(input_path)
        
    return generated_files

def run_mulval_docker(output_dir: str):
    """
    Runs the MulVAL graph generator via the wilbercui/mulval docker image for each window.
    """
    success = True
    for w in range(5):
        print(f"  [MulVAL] Running Docker container for Window {w}...")
        # Copy input_w{w}.P to input.P because graph_gen.sh expects a specific file or we just pass the filename
        input_file = f"input_w{w}.P"
        cmd = (
            f"docker run --rm --platform linux/amd64 -v {output_dir}:/input "
            f"wilbercui/mulval:latest bash -c 'cd /input && graph_gen.sh {input_file} -v'"
        )
        try:
            res = subprocess.run(cmd, shell=True, capture_output=True, text=True, timeout=30)
            if res.returncode != 0:
                if "No attack paths found" in res.stderr or "No attack paths found" in res.stdout:
                    print(f"  [MulVAL] No attack paths found for W{w} (expected if attack goal unmet).")
                else:
                    print(f"  [MulVAL] Docker execution failed for W{w}:\n{res.stderr}")
                    success = False
            else:
                # Rename the output CSVs so they don't get overwritten by the next window
                v_path = os.path.join(output_dir, "VERTICES.CSV")
                a_path = os.path.join(output_dir, "ARCS.CSV")
                if os.path.exists(v_path):
                    shutil.move(v_path, os.path.join(output_dir, f"VERTICES_w{w}.CSV"))
                if os.path.exists(a_path):
                    shutil.move(a_path, os.path.join(output_dir, f"ARCS_w{w}.CSV"))
        except Exception as e:
            print(f"  [MulVAL] Docker execution error for W{w}: {e}")
            success = False
            
    return success

def parse_mulval_output(output_dir: str):
    """
    Parses VERTICES_w*.CSV and ARCS_w*.CSV generated by MulVAL across all windows.
    Returns dict mapping window index to (vertices, arcs).
    """
    graphs_per_window = {}
    
    for w in range(5):
        vertices = {}
        arcs = []
        
        v_path = os.path.join(output_dir, f"VERTICES_w{w}.CSV")
        a_path = os.path.join(output_dir, f"ARCS_w{w}.CSV")
        
        if not os.path.exists(v_path) or not os.path.exists(a_path):
            graphs_per_window[w] = (vertices, arcs)
            continue

        with open(v_path, 'r') as f:
            reader = csv.reader(f)
            for row in reader:
                if len(row) >= 3:
                    v_id, text, v_type = row[0], row[1], row[2]
                    vertices[v_id] = {"text": text, "type": v_type}
                    
        with open(a_path, 'r') as f:
            reader = csv.reader(f)
            for row in reader:
                if len(row) >= 2:
                    src, dst = row[0], row[1]
                    arcs.append((src, dst))
                    
        graphs_per_window[w] = (vertices, arcs)
                
    return graphs_per_window

def build_ftag_from_mulval(graphs_per_window: dict, window_duration: float = 3600.0) -> ForensicTemporalAttackGraph:
    """
    Converts a sequence of parsed MulVAL graphs into our ForensicTemporalAttackGraph formalism.
    Aggregates nodes and sets edge active_windows based on which window the edge appeared in.
    Does NOT prune the graph, preserving full topological and temporal fidelity.
    """
    num_windows = len(graphs_per_window)
    ftag = ForensicTemporalAttackGraph(
        graph_id="MulVAL_Temporal_Synthetic",
        num_windows=num_windows,
        window_duration_seconds=window_duration
    )
    
    edge_active_windows = defaultdict(set)
    global_nodes = {}
    
    # 1. Aggregate all nodes across all windows and track edge presence
    for w, (vertices, arcs) in graphs_per_window.items():
        for v_id, v_data in vertices.items():
            if v_data["type"] in ["OR", "AND", "LEAF"]:
                # Clean up the text for node naming
                node_name = v_data["text"].replace('"', '').strip()
                host = "unknown"
                if "execCode(" in node_name:
                    parts = node_name.split('(')
                    if len(parts) > 1:
                        host = parts[1].split(',')[0].strip()
                elif "attackerLocated(" in node_name:
                    parts = node_name.split('(')
                    if len(parts) > 1:
                        host = parts[1].split(',')[0].strip()
                
                # Since MulVAL node IDs can change per run/window, we use the fact text as the unique semantic ID
                unique_id = f"N_{hash(node_name) % 100000}" 
                global_nodes[unique_id] = (host, node_name)
                # Store a mapping from this window's MulVAL ID to our semantic ID
                v_data["semantic_id"] = unique_id

        # Map arcs using the semantic IDs
        for src, dst in arcs:
            if src in vertices and dst in vertices:
                src_sem = vertices[src]["semantic_id"]
                dst_sem = vertices[dst]["semantic_id"]
                # MulVAL outputs Goal -> Preconditions. Reverse to Attacker -> Goal
                edge_active_windows[(dst_sem, src_sem)].add(w)

    # 2. Add all unique nodes to F-TAG
    for sem_id, (host, node_name) in global_nodes.items():
        ftag.add_node(sem_id, host_ip=host, state_name=node_name)
            
    # 3. Add edges with their temporally active windows
    edge_idx = 0
    for (src, dst), active_wins in edge_active_windows.items():
        edge_id = f"E_mulval_{edge_idx}"
        ftag.add_edge(
            edge_id=edge_id,
            src_node_id=src,  
            dst_node_id=dst,
            classification="MulVAL_Causal_Link",
            active_windows=active_wins,
            delta_t_min=1.0
        )
        edge_idx += 1
        
    return ftag
